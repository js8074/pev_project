
`timescale 1ns / 1ps

//*****************************************************************
//*****************************************************************
module svga_tb();
    
    reg r_pix_clk;      
    
    reg[3:0] r4_red;
    reg[3:0] r4_green;
    reg[3:0] r4_blue;
    
    reg[10:0] r11_x_pos;
    reg[10:0] r11_y_pos;
    
    wire[3:0] w4_red;
    wire[3:0] w4_green;
    wire[3:0] w4_blue;
    
    wire w_hsync;           
    wire w_vsync;
   
   //*****************************************************************
   //*****************************************************************
   // top module instantiation
   //*****************************************************************
   //*****************************************************************
   svga U2(

        .iw_pix_clk(r_pix_clk),          
    
        .iw4_red(r4_red),
        .iw4_green(r4_green),
        .iw4_blue(r4_blue),
    
        .iw11_x_pos(r11_x_pos),
        .iw11_y_pos(r11_y_pos),
    
        .ow4_red(w4_red),
        .ow4_green(w4_green),
        .ow4_blue(w4_blue),
    
        .ow_hsync(w_hsync),           
        .ow_vsync(w_vsync)            
    );          
    
    //*****************************************************************
    // CLK generator - if needed
    //*****************************************************************
    always begin
    
        r_pix_clk <= 0;
        #1;             //10 ns  = 100 MHz
        r_pix_clk <= 1;
        #1;
    end
    
    //*****************************************************************
    //*****************************************************************
    // INITIAL
    //*****************************************************************
    //*****************************************************************
    initial begin
    
        #100;
        
        r4_red   <= 1;
        r4_green <= 2;
        r4_blue  <= 3;
    
        r11_x_pos <= 10;
        r11_y_pos <= 10;
        
        #633168;
        $finish;
	end
	
endmodule
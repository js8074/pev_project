
`timescale 1ns / 1ps

//*****************************************************************
//*****************************************************************
module top(

    //*****************************************************************
    // CLOCK
    //*****************************************************************
    input wire iw_clk,
    
    //*****************************************************************
    // BUTTONS
    //*****************************************************************		
    input wire iw_btn0,
    input wire iw_btn1,
    input wire iw_btn2,
    input wire iw_btn3,
    
    //*****************************************************************
    // LEDS
    //*****************************************************************		 
    output wire ow_led2,
    output wire ow_led3,
    output wire ow_led4,
    output wire ow_led5,
    
    //*****************************************************************
    // UART
    //*****************************************************************		
    output wire ow_tx_start,
    output wire[7:0] ow8_tx_byte,
    input wire iw_tx_done,
    
    //*****************************************************************
    // VGA
    //*****************************************************************		
    output wire[3:0] ow4_red,
    output wire[3:0] ow4_green,
    output wire[3:0] ow4_blue,
    
    output wire[10:0] ow11_x_pos,
    output wire[10:0] ow11_y_pos);
    
    //*****************************************************************
    //*****************************************************************
    
    localparam CursorSize = 10;
    localparam Ha = 800;
	localparam Va = 600;
	
	//*****************************************************************
    
    reg r_btn01;
    reg r_btn02;
    reg r_btn0;
    wire w_btn0;
    
    reg r_btn11;
    reg r_btn12;
    reg r_btn1;
    wire w_btn1;
    
    reg r_btn21;
    reg r_btn22;
    reg r_btn2;
    wire w_btn2;
    
    reg r_btn31;
    reg r_btn32;
    reg r_btn3;
    wire w_btn3;
    
    //*****************************************************************
    
    reg r_led2;
    reg r_led3;
    reg r_led4;
    reg r_led5;
    
    reg r_tx_start;
    reg[7:0] r8_tx_byte;
    reg[7:0] r8_tx_bytes_count;
    
    reg[3:0] r4_red;
    reg[3:0] r4_green;
    reg[3:0] r4_blue;
    
    reg[10:0] r11_x_pos;
    reg[10:0] r11_y_pos;
    
    reg[27:0] r28_svga_prescaler;
    
    reg[3:0] r4_State2;
    reg[3:0] r4_State3;
    reg[3:0] r4_State4;
    reg[3:0] r4_State5;
    
    reg[3:0] r4_UartState;
    
    //*****************************************************************
    
    assign ow_led2 = r_led2;
    assign ow_led3 = r_led3;
    assign ow_led4 = r_led4;
    assign ow_led5 = r_led5;
    
    //*****************************************************************
    
    assign ow_tx_start = r_tx_start; 
    assign ow8_tx_byte = r8_tx_byte;
    
    //*****************************************************************
    
    assign ow4_red   = r4_red;
    assign ow4_green = r4_green;
    assign ow4_blue  = r4_blue;
    
    assign ow11_x_pos = r11_x_pos;
    assign ow11_y_pos = r11_y_pos;
    
    //*****************************************************************
    //*****************************************************************
    // INITIAL
    //*****************************************************************
    //*****************************************************************
    initial begin

        r_btn01 <= 0;
        r_btn02 <= 0;
        r_btn0  <= 0;
   
        r_btn11 <= 0;
        r_btn12 <= 0;
        r_btn1  <= 0;
        
        r_btn21 <= 0;
        r_btn22 <= 0;
        r_btn2  <= 0;
    
        r_btn31 <= 0;
        r_btn32 <= 0;
        r_btn3  <= 0;
        
        //*****************************************************************
        
        r_led2 <= 0;
        r_led3 <= 0;
        r_led4 <= 0;
        r_led5 <= 0;
        
        //*****************************************************************
        
        r_tx_start <= 0;
        r8_tx_byte <= 0;
        r8_tx_bytes_count <= 0;
        
        //*****************************************************************
        
        r4_red   <= 15;
        r4_green <= 15;
        r4_blue  <= 15;
        
        r11_x_pos <= 1;
        r11_y_pos <= 1;
    
        r28_svga_prescaler <= 0;
        
        //*****************************************************************
        
        r4_State2 <= 0;
        r4_State3 <= 0;
        r4_State4 <= 0;
        r4_State5 <= 0;
        
        r4_UartState <= 0;
	end
	
	
	//*****************************************************************   
    //*****************************************************************
    // Synchronize external signals with internal clock
    //*****************************************************************
    //*****************************************************************
    always @ ( negedge iw_clk ) begin
    
        r_btn01 <= iw_btn0;
        r_btn02 <= r_btn01;
        r_btn0  <= r_btn02;
        
        r_btn11 <= iw_btn1;
        r_btn12 <= r_btn11;
        r_btn1  <= r_btn12;
       
        r_btn21 <= iw_btn2;
        r_btn22 <= r_btn21;
        r_btn2  <= r_btn22;
        
        r_btn31 <= iw_btn3;
        r_btn32 <= r_btn31;
        r_btn3  <= r_btn32;
    end
    
    //*****************************************************************
    
    assign w_btn0 = r_btn0;
    assign w_btn1 = r_btn1;
    assign w_btn2 = r_btn2;
    assign w_btn3 = r_btn3;
    
    
	//*****************************************************************
	//*****************************************************************
	// LED2
	//*****************************************************************
    //*****************************************************************    
    always @ ( negedge iw_clk ) begin
   
        case( r4_State2 )
            
            //*****************************************************************
            // State 0 
            //*****************************************************************  
            0 : begin
            
                r_led2 <= 0;
               
                //*****************************************************************
                
                r4_State2 <= 1;
            end
            
            //*****************************************************************
            // State 1
            //*****************************************************************  
            1 : begin
        
                if( w_btn0 == 1 ) begin
                
                    if( r_led2 == 0 )
                        r_led2 <= 1;
                    else
                        r_led2 <= 0;
                    
                    //*****************************************************************
                    r4_State2 <= 2;
                end  
            end
            
            //*****************************************************************
            // State 2
            //*****************************************************************  
            2 : begin
        
                if( w_btn0 == 0 )
                    r4_State2 <= 1;
            end
            
            //*****************************************************************
            // Default  
            //*****************************************************************
            default : begin
            
                r4_State2 <= 0;
            end
           
        endcase          
    end
    
    
    //*****************************************************************
	//*****************************************************************
	// LED3
	//*****************************************************************
    //*****************************************************************    
    always @ ( negedge iw_clk ) begin
   
        case( r4_State3 )
            
            //*****************************************************************
            // State 0 
            //*****************************************************************  
            0 : begin
            
                r_led3 <= 0;
               
                //*****************************************************************
                
                r4_State3 <= 1;
            end
            
            //*****************************************************************
            // State 1
            //*****************************************************************  
            1 : begin
        
                if( w_btn1 == 1 ) begin
                
                    if( r_led3 == 0 )
                        r_led3 <= 1;
                    else
                        r_led3 <= 0;
                    
                    //*****************************************************************
                    
                    if( r4_red < 15 )
                        r4_red <= r4_red + 1;
                    else
                        r4_red <= 0;
                    
                    //*****************************************************************
                    r4_State3 <= 2;
                end  
            end
            
            //*****************************************************************
            // State 2
            //*****************************************************************  
            2 : begin
        
                if( w_btn1 == 0 )
                    r4_State3 <= 1;
            end
            
            //*****************************************************************
            // Default  
            //*****************************************************************
            default : begin
            
                r4_State3 <= 0;
            end
           
        endcase          
    end
    
    
    //*****************************************************************
	//*****************************************************************
	// LED4
	//*****************************************************************
    //*****************************************************************    
    always @ ( negedge iw_clk ) begin
   
        case( r4_State4 )
            
            //*****************************************************************
            // State 0 
            //*****************************************************************  
            0 : begin
            
                r_led4 <= 0;
               
                //*****************************************************************
                
                r4_State4 <= 1;
            end
            
            //*****************************************************************
            // State 1
            //*****************************************************************  
            1 : begin
        
                if( w_btn2 == 1 ) begin
                
                     if( r_led4 == 0 )
                        r_led4 <= 1;
                    else
                        r_led4 <= 0;
                    
                    //*****************************************************************
                    
                    if( r4_green < 15 )
                        r4_green <= r4_green + 1;
                    else
                        r4_green <= 0;
                        
                    //*****************************************************************
                    
                    r4_State4 <= 2;
                end  
            end
            
            //*****************************************************************
            // State 2
            //*****************************************************************  
            2 : begin
        
                if( w_btn2 == 0 )
                    r4_State4 <= 1;
            end
            
            //*****************************************************************
            // Default  
            //*****************************************************************
            default : begin
            
                r4_State4 <= 0;
            end
           
        endcase          
    end
    
    
    //*****************************************************************
	//*****************************************************************
	// LED5
	//*****************************************************************
    //*****************************************************************    
    always @ ( negedge iw_clk ) begin
   
        case( r4_State5 )
            
            //*****************************************************************
            // State 0 
            //*****************************************************************  
            0 : begin
            
                r_led5 <= 0;
               
                //*****************************************************************
                
                r4_State5 <= 1;
            end
            
            //*****************************************************************
            // State 1
            //*****************************************************************  
            1 : begin
        
                if( w_btn3 == 1 ) begin
                
                     if( r_led5 == 0 )
                        r_led5 <= 1;
                    else
                        r_led5 <= 0;
                    
                    //*****************************************************************
                    
                    if( r4_blue < 15 )
                        r4_blue <= r4_blue + 1;
                    else
                        r4_blue <= 0;
                        
                    //*****************************************************************
                    
                    r4_State5 <= 2;
                end  
            end
            
            //*****************************************************************
            // State 2
            //*****************************************************************  
            2 : begin
        
                if( w_btn3 == 0 )
                    r4_State5 <= 1;
            end
            
            //*****************************************************************
            // Default  
            //*****************************************************************
            default : begin
            
                r4_State5 <= 0;
            end
           
        endcase          
    end
    
    
    //*****************************************************************
	//*****************************************************************
	// UART TX
	//*****************************************************************
    //*****************************************************************    
    always @ ( negedge iw_clk ) begin
    
        case( r4_UartState )
            
            //*****************************************************************
            // State 0 
            //*****************************************************************  
            0 : begin
            
                r_tx_start <= 0;               
                r8_tx_byte <= 0;
                
                r8_tx_bytes_count <= 0;

                //*****************************************************************
                r4_UartState <= 1;
            end
            
            //*****************************************************************
            // State 1
            //*****************************************************************  
            1 : begin
           
                if( iw_btn0 == 1 ) begin        //wait BTN0 pressed
           
                    //*****************************************************************
                    r4_UartState <= 2;     
                end    
            end
            
            //*****************************************************************
            // State 2
            //*****************************************************************  
            2 : begin
           
                if( iw_btn0 == 0 ) begin        //wait BTN0 released
           
                    //*****************************************************************
                    r4_UartState <= 3;     
                end    
            end
            
            //*****************************************************************
            // State 3
            //*****************************************************************  
            3 : begin
           
                r8_tx_byte <= 8'h30;            //set first TX byte
                    
                //*****************************************************************
                r4_UartState <= 4;             
            end
            
            //*****************************************************************
            // State 4
            //*****************************************************************  
            4 : begin
            
                r_tx_start <= 1;                //start TX
                
                //*****************************************************************
                r4_UartState <= 5;    
            end
            
            //*****************************************************************
            // State 5
            //*****************************************************************  
            5 : begin
            
                if( r_tx_start == 1 )
                    r_tx_start <= 0;
                
                //*****************************************************************
                // BYTE SENT
                //*****************************************************************
                if( iw_tx_done == 1 ) begin
                    
                    r8_tx_bytes_count <= r8_tx_bytes_count + 1;
                    
                    //*****************************************************************
                    r4_UartState <= 6;
                end     
            end
            
            //*****************************************************************
            // State 6
            //*****************************************************************  
            6 : begin
            
                //*****************************************************************
                // PACKET SENT
                //*****************************************************************
                if( r8_tx_bytes_count == 10 ) begin      
                     
                    //*****************************************************************
                    r4_UartState <= 7;
                end
                
                //*****************************************************************
                // TX NEXT BYTE
                //*****************************************************************    
                else begin  
                    
                    r8_tx_byte <= r8_tx_byte + 1;
                    
                    //*****************************************************************        
                    r4_UartState <= 4; 
                end
            end
            
            //*****************************************************************
            // State 7
            //*****************************************************************  
            7 : begin
            
                //*****************************************************************
                r4_UartState <= 0;  
            end
            
            //*****************************************************************
            // Default  
            //*****************************************************************
            default : begin
            
                r4_UartState <= 0;
            end
           
        endcase          
    end
    
    
    //*****************************************************************
	//*****************************************************************
	// VGA
	//*****************************************************************
    //*****************************************************************    
    always @ ( negedge iw_clk ) begin
    
        if( r28_svga_prescaler < 10_000_000 )                //50 ms
            r28_svga_prescaler <= r28_svga_prescaler + 1;
            
        //*****************************************************************
            
        else begin
            
            r28_svga_prescaler <= 0;
            
            if( r11_x_pos < (Ha - CursorSize - 1) )
                r11_x_pos <= r11_x_pos + CursorSize;        //next column
                
            else begin    
                r11_x_pos <= 1;  
                
                if( r11_y_pos < (Va - CursorSize - 1) )     //next line
                    r11_y_pos <= r11_y_pos + CursorSize;
                else    
                    r11_y_pos <= 1;
            end  
        end      
    end
    
   
endmodule


`timescale 1ns / 1ps

//*****************************************************************   
//*****************************************************************   
module uart_tx_byte(

    input wire iw_clk,
    
    input wire iw_tx_start,
    input wire[7:0] iw8_tx_byte,
     
    output wire ow_tx_pin,
    output wire ow_tx_done);
  
  
    //*****************************************************************  
    //***************************************************************** 
    localparam CLKS_PER_BIT = 200;         //1 Mbaud @ 200 MHz
    
    localparam START_BIT = 1'b0;
    localparam STOP_BIT  = 1'b1;
    
    //***************************************************************** 
     
    reg r_tx_pin;
    reg r_tx_done;
     
    reg[8:0] r9_clock_div;                  //max CLKS_PER_BIT = 511 !!!
    reg[3:0] r4_bit_index;
    reg[9:0] r10_tx_buffer;
    
    reg[2:0] r3_State;
    
    assign ow_tx_pin = r_tx_pin;
    assign ow_tx_done = r_tx_done;
    
    //*****************************************************************
    //*****************************************************************
    initial begin
        
        r_tx_pin <= 1;     //Drive Tx Line High
        r_tx_done <= 0;        
        
        r9_clock_div <= 0;
        r4_bit_index <= 0; 
        r10_tx_buffer <= 0;
        
        r3_State <= 0;
    end
    
    
    //*****************************************************************  
    // TX state machine
    //***************************************************************** 
    always @ ( posedge iw_clk ) begin
       
        case( r3_State )
        
            //*****************************************************************
            // State 0 
            //*****************************************************************  
            0 : begin
                
                r_tx_pin <= 1;       
                r_tx_done <= 0;        
                
                r9_clock_div <= 0;
                r4_bit_index <= 0; 
                r10_tx_buffer <= 0;
                
                r3_State <= 1;
            end
            
            //*****************************************************************
            // State 1 
            //*****************************************************************  
            1 : begin
            
                if( iw_tx_start == 1 ) begin
                
                    r10_tx_buffer <= {STOP_BIT, iw8_tx_byte, START_BIT};
                    
                    r3_State <= 2;
                end
            end
             
            //*****************************************************************   
            // State 2
            //*****************************************************************           
            2 : begin
            
                r_tx_pin <= r10_tx_buffer[r4_bit_index];
                
                r3_State <= 3;
            end
              
            //*****************************************************************   
            // State 3
            //*****************************************************************           
            3 : begin
            
                if( r9_clock_div < (CLKS_PER_BIT-2) )
                    r9_clock_div <= r9_clock_div + 1;
                    
                //*****************************************************************  
                
                else begin
                
                    r9_clock_div <= 0;
                    
                    if( r4_bit_index < 9 ) begin
                    
                        r4_bit_index <= r4_bit_index + 1;
                        
                        r3_State <= 2;      //tx next bit
                    end
                    
                    //*****************************************************************    
                    
                    else 
                        r3_State <= 4;            
                end
            end
             
           
            //*****************************************************************   
            // State 4
            //*****************************************************************  
            4 : begin
            
                r_tx_done <= 1;    //tx done
                
                r3_State <= 0;
            end
             
             
            //*****************************************************************
            // Default  
            //*****************************************************************   
            default : begin
            
                r3_State <= 0;
            end    
                
        endcase
    end
    
endmodule

